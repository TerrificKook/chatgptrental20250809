  await expect(page.getByTestId('deposit-total')).toHaveText(formatMoney(many.depositKopecks + another.depositKopecks))
  await page.getByLabel(`Количество: ${many.title}`, { exact: true }).fill('2')
  await expect(page.getByTestId('rent-total')).toHaveText(formatMoney(many.priceKopecks * 2 + another.priceKopecks))

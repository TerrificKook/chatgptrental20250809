  await expect(page.getByTestId('selection-line')).toHaveCount(2)
  const state = await readBrowserState(page)
  expect(state.selections.find(item => item.actorId === 'participant')?.lines).toEqual([{ listingId: many.id, quantity: 2 }, { listingId: another.id, quantity: 1 }])
  expect(state.selections.some(item => item.actorId === 'guest')).toBe(false)
  await switchActor(page, many.ownerId)
  await open(page, `/items/${many.slug}`)
  await expect(page.getByRole('button', { name: 'Добавить в подборку', exact: true })).toBeDisabled()
  await expect(page.getByText('Это ваша вещь. Для запроса выберите другого демо-участника.', { exact: true })).toBeVisible()

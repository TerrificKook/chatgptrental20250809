  await expect(page.getByTestId('deposit-total')).toHaveText(deposit ? formatMoney(deposit) : 'Без залога')
  await page.getByLabel('Последний день', { exact: true }).fill('2026-10-03')
  await expect(page.getByTestId('rent-total')).toHaveText(formatMoney((many.priceKopecks * 2 + another.priceKopecks) * 3))
  await expect(page.getByTestId('deposit-total')).toHaveText(deposit ? formatMoney(deposit) : 'Без залога')
  await page.getByLabel(`Количество: ${many.title}`, { exact: true }).fill(String(many.quantity + 1))
  await expect(page.getByRole('alert')).toContainText(`Доступно только ${many.quantity}`)
